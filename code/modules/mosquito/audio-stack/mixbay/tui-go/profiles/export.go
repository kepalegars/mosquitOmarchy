// RedactedKeys are the per-machine identifiers that must never reach the
// public repo. The reverse harness records them in capture metadata.
var RedactedKeys = map[string]bool{
	"bus": true, "dev": true, "devnum": true, "busnum": true,
	"serial": true, "serial_number": true, "serialnumber": true,
	"path": true, "usb_path": true, "device_path": true,
	"node": true, "sysfs": true, "hostname": true,
}

// Export writes the effective card(s) — upstream + user override — as a clean
// tree ready for a pull request. Capsules: cards/<id>/card.json, distilled
// captures, index.json, README.md and PR.md. It never copies executable files.
func Export(ids []string, dest string) (string, error) {
	if dest == "" {
		home, _ := os.UserHomeDir()
		dest = filepath.Join(home, ".local", "share", "mosquitomixbay", "export-"+time.Now().Format("20060102-150405"))
	}
	dest, err := filepath.Abs(dest)
	if err != nil {
		return "", err
	}
	if _, err := os.Stat(dest); err == nil {
		return "", fmt.Errorf("export target already exists: %s", dest)
	}
	if len(ids) == 0 {
		for _, m := range Installed() {
			ids = append(ids, m.ID)
		}
	}
	var index Index
	index.SchemaVersion = SchemaVersion
	index.Name = "mosquito mixbay profiles"
	index.Revision = time.Now().UTC().Format("2006-01-02")

	for _, id := range ids {
		card, _, err := Effective(id)
		if err != nil {
			return "", err
		}
		dir := filepath.Join(dest, "cards", id)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", err
		}
		data := Encode(card)
		if err := os.WriteFile(filepath.Join(dir, "card.json"), data, 0o644); err != nil {
			return "", err
		}
		sum := sha256.Sum256(data)
		index.Cards = append(index.Cards, IndexCard{
			ID: card.Spec.ID, Display: card.Spec.Display, Vendor: card.Spec.Vendor,
			Version: card.Spec.Version, Native: IsNative(id), Credits: card.Credits,
			Path:   "cards/" + id + "/card.json",
			SHA256: hex.EncodeToString(sum[:]),
		})
		if err := exportCaptures(id, dir, card.Captures); err != nil {
			return "", err
		}
	}
	sort.Slice(index.Cards, func(i, j int) bool { return index.Cards[i].ID < index.Cards[j].ID })
	ixData, _ := json.MarshalIndent(index, "", "  ")
	if err := os.WriteFile(filepath.Join(dest, "index.json"), append(ixData, '\n'), 0o644); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(dest, "README.md"), []byte(exportReadme(index)), 0o644); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(dest, "PR.md"), []byte(exportPR(index)), 0o644); err != nil {
		return "", err
	}
	return dest, nil
}

func exportCaptures(id, outCardDir string, captures []Capture) error {
	for _, cap := range captures {
		// Only distilled JSONL leaves the machine; anything else is ignored.
		if !strings.HasPrefix(cap.File, "captures/") || !strings.HasSuffix(cap.File, ".jsonl") {
			continue
		}
		src := filepath.Join(cardDir(id), filepath.FromSlash(cap.File))
		in, err := os.Open(src)
		if err != nil {
			continue
		}
		dstDir := filepath.Join(outCardDir, "captures")
		if err := os.MkdirAll(dstDir, 0o755); err != nil {
			in.Close()
			return err
		}
		out, err := os.Create(filepath.Join(dstDir, filepath.Base(cap.File)))
		if err != nil {
			in.Close()
			return err
		}
		sc := bufio.NewScanner(in)
		w := bufio.NewWriter(out)
		for sc.Scan() {
			line := sc.Bytes()
			var v any
			if json.Unmarshal(line, &v) == nil {
				v = redactValue(v)
				if b, err := json.Marshal(v); err == nil {
					line = b
				}
			}
			w.Write(line)
			w.WriteByte('\n')
		}
		w.Flush()
		in.Close()
		out.Close()
	}
	return nil
}

func redactValue(v any) any {
	switch t := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, val := range t {
			if RedactedKeys[strings.ToLower(k)] {
				continue
			}
			out[k] = redactValue(val)
		}
		return out
	case []any:
		for i := range t {
			t[i] = redactValue(t[i])
		}
		return t
	default:
		return v
	}
}

func exportReadme(ix Index) string {
	var b strings.Builder
	b.WriteString("# mosquito mixbay profiles — export\n\n")
	b.WriteString("Generated by `mosquito-mixbay-actions profiles-export`.\n\n")
	b.WriteString("This folder contains only card data: no executable file, no serial number,\n")
	b.WriteString("no USB bus/device path and no raw capture session. Review it, then copy\n")
	b.WriteString("`cards/<id>/` into your fork and merge the `index.json` rows.\n\n")
	b.WriteString("Cards:\n\n")
	for _, c := range ix.Cards {
		fmt.Fprintf(&b, "- `%s` — %s (%s), %s\n", c.ID, c.Display, c.Vendor, c.Version)
	}
	return b.String()
}

func exportPR(ix Index) string {
	var b strings.Builder
	b.WriteString("## Add/update interface profile(s)\n\n")
	for _, c := range ix.Cards {
		fmt.Fprintf(&b, "- `%s` — %s (%s) `%s`\n", c.ID, c.Display, c.Vendor, c.Version)
	}
	b.WriteString("\n### Checklist\n\n")
	b.WriteString("- [ ] `profile-validate` passes on every exported card\n")
	b.WriteString("- [ ] `index.json` rows updated with the new sha256\n")
	b.WriteString("- [ ] no serial numbers, bus/device paths or local usernames\n")
	b.WriteString("- [ ] no executable code, firmware, udev rule or install script\n")
	b.WriteString("- [ ] captures are distilled JSONL (raw bundles stay in a release asset)\n")
	return b.String()
}
